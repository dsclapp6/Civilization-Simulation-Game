// Writes src/agents/doorTable.ts: where a person stands to use each building's main door, measured from the interior plans of the
// building recipes (docs/INTERIORS.md), for the agents when no plans are loaded (headless runs). `npx tsx tools/door-table.ts`
// Checked against the plans by tests/agents/doorTable.test.ts.
import { writeFileSync } from 'node:fs';
import { BUILDINGS, type BuildingKind } from '../src/content/types';
import type { CultureId } from '../src/core/domain';
import { interiorPlan } from '../src/assets/interiors/plan';

export const CULTURES: CultureId[] = ['anglo', 'norse', 'franc', 'teuton', 'gael', 'cymric'];

export function doorEntries(): Record<string, [number, number, number]> {
  const out: Record<string, [number, number, number]> = {};
  for (const kind of Object.keys(BUILDINGS) as BuildingKind[]) {
    for (let lv = 1; lv <= BUILDINGS[kind].maxLevel; lv++) {
      for (const c of CULTURES) {
        const p = interiorPlan(kind, lv, c, 0);
        if (!p || p.main < 0) continue;
        const d = p.doors[p.main];
        const r = (v: number): number => Math.round(v * 100) / 100;
        out[`${kind}|${lv}|${c}`] = [r(d.sx), r(d.sz), r(Math.atan2(d.nx, d.nz))];
      }
    }
  }
  return out;
}

if (process.argv[1]?.endsWith('door-table.ts')) {
  const e = doorEntries();
  const lines = Object.entries(e).map(([k, v]) => `  '${k}': [${v.join(', ')}],`);
  writeFileSync('src/agents/doorTable.ts', `// Generated by tools/door-table.ts from the interior plans of the building recipes (docs/INTERIORS.md): where a person stands to
// use each building's main door — local x, z of the standing place and the yaw of the door's outward face — by kind|level|culture.
// The agents use it when no plans are loaded; tests/agents/doorTable.test.ts checks it against the plans.
export const DOOR_STAND: Readonly<Record<string, readonly [number, number, number]>> = {
${lines.join('\n')}
};
`);
  console.log(`${lines.length} doors`);
}
